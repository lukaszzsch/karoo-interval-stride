"""Generates ThemeOverrides.kt: every colour the interval screen's layouts set in XML, per view.

Why: the Karoo draws our data field with its own day/night setting, so colours in the layouts
resolve in the Karoo's mode. When the rider forces Dark or Light (Settings → Appearance), the
renderer re-applies each of these colours from a context in the chosen mode.

What it does:
  - gives every view that has a colour (text, icon tint, background, progress) an id if it has
    none (android:id="@+id/th_<layout>_<n>"), editing the layout files in place;
  - writes app/src/main/kotlin/.../ThemeOverrides.kt with one list of operations per layout.

Run after changing a field layout: python3 tools/gen_theme_overrides.py  (from the repo root)
"""
import pathlib, re
root = pathlib.Path(__file__).resolve().parents[1]
res = root / 'app/src/main/res'
LAYOUTS = ['field_interval', 'field_interval_gauge', 'field_interval_karoo', 'field_interval_gauge_karoo', 'field_free', 'field_free_karoo']

def drawable_color(name):
    """The colour resource a drawable is painted with (solid, else stroke/fill), or None."""
    p = res / 'drawable' / f'{name}.xml'
    if not p.exists(): return None
    s = p.read_text()
    m = (re.search(r'<solid android:color="@color/(\w+)"', s) or re.search(r'<stroke[^>]*android:color="@color/(\w+)"', s)
         or re.search(r'android:centerColor="@color/(\w+)"', s) or re.search(r'android:endColor="@color/(\w+)"', s)
         or re.search(r'android:(?:strokeColor|fillColor)="@color/(\w+)"', s))
    return m.group(1) if m else None

def progress_colors(name):
    s = (res / 'drawable' / f'{name}.xml').read_text()
    bg = re.search(r'@android:id/background[\s\S]*?android:color="@color/(\w+)"', s)
    fg = re.search(r'@android:id/progress[\s\S]*?android:color="@color/(\w+)"', s)
    return (fg.group(1) if fg else None, bg.group(1) if bg else None)

ops_by_layout, used_drawables = {}, set()
for layout in LAYOUTS:
    path = res / 'layout' / f'{layout}.xml'
    s = path.read_text()
    out, pos, n, ops = [], 0, 0, []
    for m in re.finditer(r'<([A-Za-z]+)((?:\s+[\w:]+="[^"]*")*)\s*(/?)>', s):
        tag, attrs = m.group(1), m.group(2)
        a = dict(re.findall(r'([\w:]+)="([^"]*)"', attrs))
        found = []
        if 'android:textColor' in a and a['android:textColor'].startswith('@color/'):
            found.append(('TEXT', a['android:textColor'][7:], None))
        if tag == 'ImageView':
            if a.get('android:tint', '').startswith('@color/'):
                found.append(('TINT', a['android:tint'][7:], None))
            elif a.get('android:src', '').startswith('@drawable/'):
                c = drawable_color(a['android:src'][10:])
                if c: found.append(('TINT', c, None))
        bg = a.get('android:background', '')
        if bg.startswith('@drawable/'):
            used_drawables.add(bg[10:])
            c = drawable_color(bg[10:])
            if c: found.append(('BG', c, None))
        elif bg.startswith('@color/'):
            found.append(('BG_COLOR', bg[7:], None))
        if a.get('android:progressDrawable', '').startswith('@drawable/'):
            fg, bgc = progress_colors(a['android:progressDrawable'][10:])
            if fg: found.append(('PROGRESS', fg, bgc))
        if not found: continue
        vid = a.get('android:id', '')
        if not vid:
            n += 1
            vid = f'@+id/th_{layout.replace("field_", "")}_{n}'
            # insert the id as the first attribute, on its own line, keeping the indentation
            indent = re.search(r'\n(\s*)android:', m.group(0))
            ins = f'\n{indent.group(1) if indent else " "}android:id="{vid}"'
            out.append(s[pos:m.start(2)] + ins)
            pos = m.start(2)
        ops += [(vid.split('/')[-1], k, c1, c2) for k, c1, c2 in found]
    out.append(s[pos:])
    path.write_text(''.join(out))
    ops_by_layout[layout] = ops

# Drawables the renderer swaps in at run time, and the colour each is painted with.
for p in sorted((res / 'drawable').glob('bg_*.xml')):
    used_drawables.add(p.stem)
dmap = {d: drawable_color(d) for d in sorted(used_drawables) if drawable_color(d)}

pkg = 'com.daviddokakis.karoointerval'
kt = [f'package {pkg}', '', '// GENERATED by tools/gen_theme_overrides.py from the field layouts. Do not edit by hand.', '',
      '/** Every XML colour in the field layouts, per view, to re-apply in a forced Dark / Light mode. */',
      'internal object ThemeOverrides {', '    enum class Kind { TEXT, TINT, BG, BG_COLOR, PROGRESS }', '',
      '    class Op(val id: Int, val kind: Kind, val color: Int, val color2: Int = 0)', '',
      '    fun forLayout(layout: Int): List<Op> = when (layout) {']
for layout in LAYOUTS:
    kt.append(f'        R.layout.{layout} -> {layout.upper()}')
kt += ['        else -> emptyList()', '    }', '',
       '    /** The colour each background drawable is painted with (for drawables swapped in at run time). */',
       '    val drawableColor: Map<Int, Int> = mapOf(']
kt += [f'        R.drawable.{d} to R.color.{c},' for d, c in dmap.items()]
kt += ['    )', '']
for layout in LAYOUTS:
    kt.append(f'    private val {layout.upper()} = listOf(')
    for vid, k, c1, c2 in ops_by_layout[layout]:
        extra = f', R.color.{c2}' if c2 else ''
        kt.append(f'        Op(R.id.{vid}, Kind.{k}, R.color.{c1}{extra}),')
    kt.append('    )')
    kt.append('')
kt[-1] = '}'
out = root / 'app/src/main/kotlin/com/daviddokakis/karoointerval/ThemeOverrides.kt'
out.write_text('\n'.join(kt) + '\n')
print('wrote', out, {k: len(v) for k, v in ops_by_layout.items()})
